export function TourOverlay({ onNavigate }: { onNavigate: (route: RouteId) => void }) {
  const { tourStep, setTourStep } = usePlotlineStore();
  const [rect, setRect] = useState<DOMRect | null>(null);

  const currentConfig =
    tourStep !== null ? TOUR_STEPS.find((s) => s.step === tourStep) || null : null;

  useEffect(() => {
    if (!currentConfig) {
      setRect(null);
      return;
    }

    if (currentConfig.route) {
      onNavigate(currentConfig.route);
    }

    const updateRect = () => {
      const el = document.querySelector(currentConfig.targetSelector);
      if (el) {
        const reduced =
          typeof window !== 'undefined' &&
          window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        el.scrollIntoView({
          block: 'nearest',
          behavior: reduced ? 'auto' : 'smooth',
        });
        setRect(el.getBoundingClientRect());
      } else {
        setRect(null);
      }
    };

    const timer = window.setTimeout(updateRect, 80);
    window.addEventListener('resize', updateRect);
    window.addEventListener('scroll', updateRect, true);

    return () => {
      window.clearTimeout(timer);
      window.removeEventListener('resize', updateRect);
      window.removeEventListener('scroll', updateRect, true);
    };
  }, [currentConfig, onNavigate]);

  if (!currentConfig) return null;

  const isLastStep = currentConfig.step === TOUR_STEPS.length;

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-label={`Guided tour step ${currentConfig.step} of ${TOUR_STEPS.length}`}
      data-testid="guided-tour-overlay"
      className="fixed inset-0 z-50 pointer-events-auto"
    >
      {/* Backdrop */}
      <div
        className="fixed inset-0 bg-black/35"
        onClick={() => setTourStep(null)}
        aria-hidden="true"
      />

      {/* Target Highlight Spotlight Ring */}
      {rect && (
        <div
          style={{
            top: Math.max(4, rect.top - 6),
            left: Math.max(4, rect.left - 6),
            width: rect.width + 12,
            height: rect.height + 12,
            borderColor: 'var(--accent)',
            boxShadow: '0 0 0 4px var(--accent-soft), 0 12px 32px rgba(0,0,0,0.28)',
          }}
          className="fixed z-50 rounded-[var(--radius-lg)] border-2 pointer-events-none transition-all duration-250 ease-plotline"
        />
      )}

      {/* Floating Tour Step Card */}
      <div className="fixed bottom-6 left-1/2 -translate-x-1/2 z-50 w-full max-w-md px-4">
        <div className="bg-[var(--surface-elevated)] border-2 border-[var(--accent)] rounded-[var(--radius-lg)] shadow-2xl p-5 space-y-3">
          <div className="flex items-center justify-between gap-2">
            <span
              className="px-2.5 py-0.5 rounded-full text-[11px] font-semibold"
              style={{
                backgroundColor: 'var(--accent-soft)',
                color: 'var(--accent)',
              }}
            >
              Step {currentConfig.step} of {TOUR_STEPS.length}
            </span>
            <button
              type="button"
              onClick={() => setTourStep(null)}
              aria-label="Close guided tour"
              className="p-1 rounded-[var(--radius-xs)] text-[var(--ink-muted)] hover:text-[var(--ink-primary)] cursor-pointer"
            >
              <X className="w-4 h-4" />
            </button>
          </div>

          <div>
            <h3 className="text-sm sm:text-base font-bold text-[var(--ink-primary)]">
              {currentConfig.title}
            </h3>
            <p className="text-xs text-[var(--ink-secondary)] mt-1 leading-relaxed">
              {currentConfig.description}
            </p>
          </div>

          {/* Step Dots + Controls */}
          <div className="pt-2 border-t border-[var(--border-hairline)] flex items-center justify-between gap-2">
            <div className="flex items-center gap-1.5">
              {TOUR_STEPS.map((s) => (
                <button
                  key={s.step}
                  type="button"
                  onClick={() => setTourStep(s.step)}
                  aria-label={`Jump to step ${s.step}`}
                  style={{
                    backgroundColor:
                      s.step === currentConfig.step
                        ? 'var(--accent)'
                        : 'var(--border-strong)',
                  }}
                  className="w-2 h-2 rounded-full transition-colors cursor-pointer"
                />
              ))}
            </div>

            <div className="flex items-center gap-2">
              {currentConfig.step > 1 && (
                <button
                  type="button"
                  onClick={() => setTourStep(currentConfig.step - 1)}
                  className="px-3 py-1.5 rounded-full text-xs font-medium text-[var(--ink-secondary)] hover:text-[var(--ink-primary)] hover:bg-[var(--surface-sunken)] cursor-pointer"
                >
                  Previous
                </button>
              )}
              <button
                type="button"
                onClick={() =>
                  isLastStep ? setTourStep(null) : setTourStep(currentConfig.step + 1)
                }
                style={{ backgroundColor: 'var(--accent)' }}
                className="px-4 py-1.5 rounded-full text-xs font-semibold text-white hover:opacity-95 cursor-pointer"
              >
                {isLastStep ? 'Finish tour' : 'Next step'}
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}

